let restoreClock: (() => void) | undefined;
type SettledStart = { ok: true; result: WorkflowAdvanceResult } | { ok: false; error: unknown };
const pendingStarts: Array<Promise<SettledStart>> = [];

export async function cleanupWP1Scenarios(): Promise<void> {
  try {
    await cleanupScenarios();
    // Crashed Hosts may return a stale-write refusal when drained. They are
    // never used as evidence for the live Host, but every HTTP promise settles.
    await Promise.all(pendingStarts.splice(0));
  } finally {
    restoreClock?.();
    restoreClock = undefined;
  }
}

async function checkStep(h: HostScenario, input: WorkflowAdvanceInput, value: ScenarioStepValue): Promise<void> {
  const label = `${input.flowId}: ${input.kind === 'perform' ? input.operation.kind : input.kind}`;
  const step = value.receipt === null ? undefined
    : stepOfReceipt(value.receipt, h.stepActor(), h.automationPolicy(), label);
  // L10: new W operations use the automation principal; the old harness does
  // not know their names. This is classification only, never a stub owner.
  const kind: string = input.kind === 'perform' ? input.operation.kind : input.kind;
  if (step !== undefined && (kind === 'transfer_responsibility' || kind === 'archive_predecessor')) {
    step.actor = { ...WORKFLOW_AUTOMATION_ACTOR };
  }
  await assertInvariants(h, label, step);
}

/** No step-kind switch: W steps pass through the real route just like old ones. */
async function drive(h: HostScenario, first: WorkflowAdvanceInput,
  stopBefore?: (input: WorkflowAdvanceInput) => boolean, carry?: ScenarioDrive): Promise<ScenarioDrive> {
  const trace: ScenarioDrive = carry ?? { inputs: [], performedKinds: [], steps: [], receipts: [],
    state: 'bounded', reason: null, next: first };
  let input = first;
  for (let index = 0; index < 60; index += 1) {
    if (stopBefore?.(input) === true) return { ...trace, state: 'stopped', next: input };
    trace.inputs.push(input);
    if (input.kind === 'perform') trace.performedKinds.push(input.operation.kind);
    const result = await h.post<WorkflowAdvanceResult>('workflow/advance', plain(AG2B_SCOPE, input));
    const value = ready(result);
    trace.steps.push(value);
    if (value.receipt !== null) trace.receipts.push(value.receipt);
    await checkStep(h, input, value);
    if (value.state !== 'advance' || value.next === null) {
      return { ...trace, state: value.state, reason: value.reason, next: value.next };
    }
    input = value.next;
  }
  return { ...trace, state: 'bounded', reason: 'the 60-step bound was reached', next: input };
}

type HeldWork = {
  h: HostScenario; held: HeldReply; setup: ScenarioDrive; start: WorkflowAdvanceInput;
  pending: Promise<SettledStart>; runRef: RunRef; P: SessionRef; running: TaskExecutionRecord;
};

async function openHeldWork(id: string): Promise<HeldWork> {
  restoreClock ??= installS1ScenarioClock();
  const h = await openHostScenario({ automation: NO_REDRIVE, check: 'pass', script: { replies: [
    readCall(`${id}-entered`), readCall(`${id}-held`), textReply(`${id}: successor completes the work`),
  ] } });
  await assertInvariants(h, `${id}: real seed`);
  const held = h.holdReply(1);
  const setup = await drive(h, h.select(id, AG2B_WORK_TASK_ID), performs('start'));
  const start = setup.next;
  if (start === null || !performs('start')(start)) throw new Error(`${id}: setup did not reach start`);
  const pending = h.post<WorkflowAdvanceResult>('workflow/advance', plain(AG2B_SCOPE, start))
    .then(result => ({ ok: true as const, result }), (error: unknown) => ({ ok: false as const, error }));
  pendingStarts.push(pending);
  await Promise.race([held.reached, pending.then(result => {
    throw new Error(`${id}: start settled before the held second reply: ${JSON.stringify(result)}`);
  })]);
  await assertInvariants(h, `${id}: entered, first tool finished, second reply held`, stepOf(h, 'entry_authorized', id));
  const runRef = await selectedRun(h);
  const running = await execution(h, runRef);
  const P = { projectId: running.session.ref.projectId, sessionId: running.session.ref.sessionId };
  return { h, held, setup, start, pending, runRef, P, running };
}

/** Read-only SQLite SELECT, as support/restart.ts; decode through the real codec. */
function archiveRequests(h: HostScenario, P: SessionRef): ArchiveRequestObservation[] {
  return readSqlite<ArchiveRequestObservation[]>(join(h.database, 'ledger.sqlite'), db => {
    const found: ArchiveRequestObservation[] = [];
    for (const row of db.prepare('SELECT id, event_json FROM events ORDER BY id').all()) {
      if (typeof row.event_json !== 'string') throw new Error('event_json must be text');
      // SQLite stores the body, not an EncodedDomainEvent with a nested json
      // field (the same envelope reconstruction as invariants.ts:487-490).
      const envelope = decodeStoredEventBody(row.event_json);
      if (envelope.status !== 'decoded') throw new Error(envelope.reason);
      if (envelope.value.event.eventType !== 'SessionArchiveRequested') continue;
      const decoded = sessionArchiveChangedEventFromEvent(envelope.value.event);
      if (decoded.status !== 'decoded') throw new Error(decoded.reason);
      const body = decoded.value;
      if (body.session.ref.projectId !== P.projectId || body.session.ref.sessionId !== P.sessionId) continue;
      const request = body.session.archiveRequest;
      if (request === null || request === undefined) throw new Error('archive-requested event has no request');
      found.push({ cursor: makeCommitCursor(Number(row.id)), requestId: request.requestId, mode: request.mode, request });
    }
    return found;
  }, []);
}

async function observations(work: HeldWork): Promise<ScenarioObservations> {
  const { h, P, runRef, setup, running } = work;
  const platform = await h.direct();
  const ctx = hostCtx(h.stepActor());
  const readWorld = () => readInvariantWorld(invariantStoreOf(h.database), AG2B_SCOPE.projectId);
  const readAnomalies = async (): Promise<SessionAnomalyViewV1[]> => {
    const all: SessionAnomalyViewV1[] = [];
    let cursor: string | null = null;
    for (let page = 0; page < 25; page += 1) {
      const result: SessionPage<SessionAnomalyViewV1> = ready(await h.post<ReadResult<SessionPage<SessionAnomalyViewV1>>>('anomalies/list', plain(AG2B_SCOPE,
        { goalRef: AG2B_GOAL_REF, page: cursor === null ? { limit: 100 } : { limit: 100, cursor } })));
      all.push(...result.items);
      if (result.nextCursor === null) return all;
      cursor = result.nextCursor;
    }
    throw new Error('the anomaly observation exceeded 25 pages');
  };
  return { harness: h, platform, ctx, P, T: WORK_TARGET.ref, goalRef: AG2B_GOAL_REF, runRef, setup, running,
    readSession: async () => ready(await h.post<ReadResult<SessionCard>>('sessions/read', plain(AG2B_SCOPE, P))),
    readExecution: () => execution(h, runRef), readTask: () => h.taskRow(),
    readArchiveRequests: () => archiveRequests(h, P), readAnomalies,
    // Includes picked-up historical anchors; never confuses an empty pending index with no records.
    readAnchors: async () => (await readWorld()).anchors ?? [],
    readRequeues: async () => (await readWorld()).requeues.filter(r => r.task.taskId === AG2B_WORK_TASK_ID),
    readWorld,
    readArchiveState: () => h.post<Awaited<ReturnType<SessionAnomalyPort['readTaskArchiveState']>>>(
      'tasks/archive-state', plain(AG2B_SCOPE, WORK_TARGET.ref)),
    counts: () => ({ files: h.counts(), ledger: ledgerCounts(h.database) }),
  };
}

export async function openPausedInterruptedScenario(): Promise<PausedInterruptedScenario> {
  const work = await openHeldWork('wp1-sc01');
  const { h, runRef } = work;
  // A8-3m: queue only; do NOT release the held reply or deliver another safe point.
  const pause = await submitControl(h.host, runRef, 'pause', 'SC01: pause the running work', 'wp1-sc01-pause');
  await assertInvariants(h, 'SC01: human pause queued', stepOf(h, 'other', 'SC01 pause'));
  const pauseBeforeRestart = await readControl(h.host, pause.intent.ref);
  await h.restart({ crash: true });
  const reconciled = await execution(h, runRef);
  const base = await observations(work);
  // Exercise maintenance while the original pause fence still holds, without continuing T.
  const fenced = await drive(h, h.select('wp1-sc01-paused', AG2B_WORK_TASK_ID));
  if (fenced.state !== 'waiting') throw new Error(`SC01: paused selection did not wait: ${JSON.stringify(fenced)}`);
  let claimed: ScenarioDrive | undefined;
  return { ...base, pause, pauseBeforeRestart, reconciled,
    clickContinue: async () => {
      const body = await requeueBodyOf(h.host, runRef, 'wp1-sc01-continue', '继续');
      const result = await h.post<WriteResult<TaskRequeueOutcomeV1>>('tasks/requeue', body);
      await assertInvariants(h, 'SC01: human continue', stepOf(h, 'task_requeued', 'SC01 continue'));
      return result;
    },
    // K-W KA-07: stop after the continuation re-claim commits, before its start.
    advanceUntilClaimed: async () => {
      claimed = await drive(h, h.select('wp1-sc01-claim'), performs('start'));
      return claimed;
    },
    // Goal-level selection runs work, stage and Goal gates without a second model Run.
    advanceToEnd: async () => {
      const carry = claimed;
      claimed = undefined;
      if (carry === undefined) return drive(h, h.select('wp1-sc01-finish'));
      if (carry.next === null) throw new Error('SC01: the drive did not stop before start');
      return drive(h, carry.next, undefined, carry);
    },
  };
}

export async function openArchivedLineScenario(): Promise<ArchivedLineScenario> {
  const work = await openHeldWork('wp1-sc02');
  const { h, P } = work;
  const base = await observations(work);
  const beforeArchiveAnchors = await base.readAnchors();
  const card = await base.readSession();
  const archiveRequest: GraphWrite<ArchiveLineInput> = { input: { sessionRef: P,
    reason: 'SC02: the operator archives the running line', tasks: [{ target: WORK_TARGET, disposition: { kind: 'drop' } }],
    wait: null }, meta: { requestId: 'wp1-sc02-archive', expected: [{ ref: card.record.ref, revision: card.record.revision }] } };
  const archiveResults = [ready(await h.post<ReadResult<ArchiveLineResultV1>>('sessions/archive-line',
    { scope: AG2B_SCOPE, request: archiveRequest }))];
  await assertInvariants(h, 'SC02: operator archive requested and cancel submitted');
  // Let the real Runtime observe the committed cancellation. No terminal fact is injected.
  work.held.release();
  const settled = await work.pending;
  if (!settled.ok) throw settled.error;
  const stoppedStart = ready(settled.result);
  await checkStep(h, work.start, stoppedStart);
  archiveResults.push(ready(await h.post<ReadResult<ArchiveLineResultV1>>('sessions/archive-continue',
    plain(AG2B_SCOPE, { sessionRef: P, archiveRequestId: archiveRequest.meta.requestId }))));
  await assertInvariants(h, 'SC02: archive continuation, anchor/drop/requeue/final archive');
  const anchors = await base.readAnchors();
  const A = anchors.find(anchor => anchor.runRef.runId === work.runRef.runId);
  if (A === undefined) throw new Error('SC02: the existing archive owner did not produce the given anchor');
  let preparedState: PreparedScenario | undefined;
  return { ...base, A, beforeArchiveAnchors, archiveRequest, archiveResults, stoppedStart,
    advanceUntilPrepared: async () => {
      const advanced = await drive(h, h.select('wp1-sc02-pickup'), performs('start'));
      const prepared = preparedOf(advanced.next);
      const manifest = manifestOf(h.database, prepared.envelope.bundleRef.digest);
      const binding = manifest.contextAssembly;
      if (binding === undefined) throw new Error('SC02: the existing S3 preparation returned no context binding');
      if (advanced.next === null) throw new Error('SC02: no prepared start to return');
      preparedState = { drive: advanced, prepared, manifest, binding, input: manifest.input,
        successor: prepared.claim.sessionRef, runRef: prepared.claim.runRef, next: advanced.next };
      return preparedState;
    },
    enterAndComplete: async () => {
      if (preparedState === undefined) throw new Error('call advanceUntilPrepared() before enterAndComplete()');
      return drive(h, preparedState.next);
    },
    readGoalContextFacts: () => base.platform.graphContext.readContextFacts(base.ctx,
      { goalRef: AG2B_GOAL_REF, focusTaskIds: [AG2B_WORK_TASK_ID] }),
  };
}
