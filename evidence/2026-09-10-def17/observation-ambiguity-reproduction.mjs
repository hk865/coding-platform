import { RuntimeObservationJournal } from '../../dist/vault/runtime-observation-journal.js';
import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const directory = fileURLToPath(new URL('./observation-ambiguity-fixture/', import.meta.url));
await mkdir(directory, { recursive: true });
const spec = { projectId: 'audit', goalId: 'audit', runId: 'audit-review', workspaceId: 'audit', taskId: 'audit' };
const keyFor = r => createHash('sha256').update(JSON.stringify([r.spec.projectId, r.spec.goalId, r.spec.runId])).digest('hex');
const unknown = { spec, status: 'outcome_unknown', events: [], trace: [], usage: [], sessionId: 'audit-session' };
const failed = { ...unknown, status: 'failed', events: [{ eventType: 'run_crashed', sequence: 1 }], error: 'prestart' };
await writeFile(join(directory, '0'.repeat(64) + '.json'), JSON.stringify(unknown));
await writeFile(join(directory, 'f'.repeat(64) + '.json'), JSON.stringify(failed));
const journal = new RuntimeObservationJournal(directory, { keyFor, serialize: JSON.stringify, writeOrder: 'per_record' });
await journal.init();
const rows = journal.observations.all();
const result = { persistedFiles: 2, sameRunIdentity: true, publicRows: rows.length, publicStatus: rows[0]?.status, scope: 'Read production built journal with isolated malformed duplicate observations; no product running data changed.' };
console.log(JSON.stringify(result));
await writeFile(new URL('./observation-ambiguity-result.json', import.meta.url), JSON.stringify(result, null, 2) + '\n');
