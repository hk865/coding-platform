  /* the moments this board pasted (one data method above, normally) */
  wlSnapshot() {
    if (this._wlSnap) return this._wlSnap;
    const S = {}; [['main', 'wlSnapMain'], ['decide', 'wlSnapDecide'], ['chain', 'wlSnapChain'], ['plan', 'wlSnapPlan'], ['done', 'wlSnapDone']]
      .forEach((p) => { if (typeof this[p[1]] === 'function') S[p[0]] = this[p[1]](); });
    this._wlSnap = S;
    return S;
  }
  /* the snapshot of a moment (default main; a board with one data method gets that one whatever it asks) */
  wlSnap(at) { const S = this.wlSnapshot(); return S[at || 'main'] || S[Object.keys(S)[0]]; }
  /* the rail / member list (data/worklines.js wlRail(): 秘书（主对话） first, then 需要你决定 > 失败 > 受阻 > 待核对, then the most
     recent activity; archived apart; counts, head, archivedText, goalBar); ctl 'paused' / 'cancelled' where the moment has it */
  wlRail(at, ctl) {
    const s = this.wlSnap(at); const a = ctl ? s.alt[ctl] : null;
    if (!a) return s;
    const fix = (r) => (a.rows[r.id] ? Object.assign({}, r, a.rows[r.id]) : r);
    return Object.assign({}, s, { rows: s.rows.map(fix), archived: s.archived.map(fix), counts: a.counts, head: a.head, goalBar: a.goalBar });
  }
  /* 负责 of a task at that moment (hover card, detail): "执行者 · SSE 推送 · 工作中", "执行者 · 前端拆分 · 已做完，第 2 次尝试（工作记录第 2 段）" */
  wlOwner(id, at, ctl) { const s = this.wlSnap(at); const a = ctl ? s.alt[ctl] : null; return (a && a.owners[id]) || s.owners[id] || '未分配'; }
  /* 负责 of a stage, a batch or the goal: "3 条工作线做过这里的任务，1 条在做" */
  wlGroupOwner(id, at, ctl) { const s = this.wlSnap(at); const a = ctl ? s.alt[ctl] : null; return (a && a.groups[id]) || s.groups[id] || '还没有工作线做过这里的任务'; }
  /* the goal bar's reason while the goal runs: "3 条工作线工作中" (approved: "2 位成员工作中") */
  wlGoalBar(at, ctl) { return this.wlRail(at, ctl).goalBar; }
  /* the work line of a task (or of a role: 'secretary' | 'advisor' | 'reviewer'), as a rail row — for links (Chain is the
     record of 执行者 · 重新入队与失败类别, Member the page of 执行者 · SSE 推送) */
  wlLineOf(key, at, ctl) {
    const R = this.wlRail(at, ctl); const all = R.rows.concat(R.archived);
    return all.filter((r) => r.task === key || r.role === key || r.id === key)[0] || null;
  }
  /* 负责 of an architecture node (the 负责的 Agent row of a module's, folder's or semantic group's card and detail). The sample
     data has no 模块维护 line (decision 25 names it as a long-lived role), so the row says which work lines changed files
     under it: "7 条工作线改过这里的文件，2 条在做" (the approved row named one of the two old executors and its word).
     A long-lived role's line counts with the files of its tasks that had started (wlRailAt).
     x = a module or folder path ('src/core/work-graph', 'src/app/server' …; a semantic group 'src/app#server' counts as its
     module) or the array of the node's file paths (exact). Reads only wlRail(), so it is the same in worklines-snap.js. */
  wlAreaOwner(x, at, ctl) {
    const R = this.wlRail(at, ctl); const p = Array.isArray(x) ? null : String(x).split('#')[0];
    const hit = (f) => (p === null ? x.indexOf(f) >= 0 : f === p || f.indexOf(p + '/') === 0);
    const did = R.rows.concat(R.archived).filter((r) => r.files.some(hit)); const busy = did.filter((r) => r.state === 'doing').length;
    return did.length ? did.length + ' 条工作线改过这里的文件，' + (busy ? busy + ' 条在做' : '没有在做的') : '还没有工作线改过这里的文件';
  }
  /* 负责 of the goal (its root's card and detail): the secretary runs the goal and the other lines are counted — never one
     "n 位成员" number. "秘书 · 待命，另有 3 条工作线工作中" (approved: "秘书 · 待命，另有 2 位成员工作中"); paused "…另有 3 条工作线已暂停";
     cancelled "秘书 · 待命". Reads only wlRail(), so it is the same in worklines-snap.js. */
  wlGoalOwner(at, ctl) {
    const R = this.wlRail(at, ctl); const sec = R.rows.filter((r) => r.role === 'secretary')[0];
    const doing = R.rows.filter((r) => r.role !== 'secretary' && r.state === 'doing').length; const paused = R.rows.filter((r) => r.word === '已暂停').length;
    return '秘书 · ' + (sec ? sec.word : '待命') + (doing ? '，另有 ' + doing + ' 条工作线工作中' : paused ? '，另有 ' + paused + ' 条工作线已暂停' : '');
  }
  /* the counts line again, for rows a board changed itself (its own clock: 秘书 working after 采用 on Main, 审阅者 · 规格 on
     goal 2's first task after 采用 on Plan): "工作中 4 · 待命 7 · 已归档 8". rows = wlRail().rows with the board's changes,
     archived = wlRail().archived. Reads nothing else, so it is the same in worklines-snap.js. */
  wlHeadOf(rows, archived) {
    const doing = rows.filter((r) => r.state === 'doing').length;
    return '工作中 ' + doing + ' · 待命 ' + (rows.length - doing) + ' · 已归档 ' + (archived ? archived.length : 0);
  }
  /* the record of ONE work line (decision 33): the rail row of wlLineOf() plus attempt, archived, segs and its entries in
     time order — the same as data/worklines.js wlRecord() (see there for every field); stored per moment in recs, each entry
     as a row of the keys below, and for the goal's 暂停 / 取消 in alt.<ctl>.recs where they differ */
  wlRecord(key, at, ctl) {
    const row = this.wlLineOf(key, at, ctl);
    if (!row) return null;
    const s = this.wlSnap(at); const a = ctl ? s.alt[ctl] : null; const rec = (s.recs || {})[row.id];
    if (!rec) return null;
    const K = ["id", "kind", "task", "taskName", "att", "seg", "round", "start", "end", "day", "time", "dur", "res", "word", "tx", "label", "gap", "asker", "steps", "edits", "checks", "live"];
    const rows = (a && a.recs && a.recs[row.id]) || rec.entries;
    return Object.assign({}, row, { attempt: rec.attempt, archived: row.state === 'archived', segs: rec.segs,
      entries: rows.map((v) => { const e = {}; K.forEach((k, i) => { e[k] = v[i]; }); return e; }), acts: rec.acts || [] });
  }
