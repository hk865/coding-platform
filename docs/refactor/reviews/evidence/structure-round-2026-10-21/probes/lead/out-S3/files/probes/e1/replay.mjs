#!/usr/bin/env node
/**
 * Replays one recorded probe log against a copy's real functions and compares
 * every output with the recorded base output.
 *
 * Usage:
 *   node replay.mjs <copy-dir> <combined-log.jsonl> [--out <replayed.jsonl>]
 *                   [--report <report.json>] [--label <base|result>]
 *
 * It writes (and overwrites) `<copy-dir>/tests/probes/replay.generated.test.ts`,
 * runs only that file with `npx vitest run --maxWorkers=2`, then compares:
 * strings as UTF-8 buffers (first-difference byte offset, both lengths, 16
 * neighbouring bytes), arrays element by element with count/order, objects own
 * keys in order with missing vs undefined vs null kept apart, numbers exactly.
 * Nothing is sorted or canonicalised first.
 */
import { mkdirSync, readFileSync, unlinkSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { spawnSync } from 'node:child_process';
import { compareValues, relativeTestPath } from './lib/compare.mjs';

const args = process.argv.slice(2);
const copy = args[0];
const logFile = args[1];
if (copy === undefined || logFile === undefined) {
  console.error('usage: node replay.mjs <copy-dir> <combined-log.jsonl> [--out f] [--report f] [--label s]');
  process.exit(2);
}
function flag(name, fallback) {
  const index = args.indexOf(name);
  return index < 0 ? fallback : args[index + 1];
}
const copyDir = resolve(copy);
const inputLog = resolve(logFile);
const label = flag('--label', 'copy');
const replayOut = resolve(flag('--out', `replayed-${label}.jsonl`));
const reportPath = flag('--report', '');
mkdirSync(dirname(replayOut), { recursive: true });
mkdirSync(resolve(copyDir, 'tests/probes'), { recursive: true });

const generated = `/**
 * Generated by probes/e1/replay.mjs — copy-only. Replays every recorded call of
 * one base log through this copy's real functions.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { expect, it } from 'vitest';
import { renderContinuationBriefZh, approvedMethodLinesZh, probeBlockedCommandsLinesZh } from '../../src/contracts/continuation-brief.js';
import { renderUnknownCallReviewZh } from '../../src/contracts/core/prepared-execution.js';
import { platformRoleProfile } from '../../src/core/agent-runtime/role-profiles.js';
import { formatDecisionResponseInput } from '../../src/core/agent-runtime/execution-inputs.js';
import { architectureReminderRowEntries } from '../../src/core/agent-runtime/architecture-reminders.js';
import { renderNoteHeader } from '../../src/contracts/note.js';
import { probeConsultationGuidanceText } from '../../src/business/workflow/consultation.js';
import { probeScribeReminderText } from '../../src/app/host.js';
import { probeDecisionRowText, probeNotAvailableRowText, probeAnchorText } from '../../src/core/work-graph/views/context-extensions.js';
import { serializeProbe } from '../../src/probe-hook.js';

const inputPath = process.env['S85_REPLAY_IN'];
const outputPath = process.env['S85_REPLAY_OUT'];
if (inputPath === undefined || inputPath === '' || outputPath === undefined || outputPath === '') {
  throw new Error('S85_REPLAY_IN / S85_REPLAY_OUT are required');
}

function revive(_key: string, value: unknown): unknown {
  if (value !== null && typeof value === 'object' && (value as Record<string, unknown>)['$probe'] === 'undefined') return undefined;
  return value;
}

const records = readFileSync(inputPath, 'utf8').split('\\n').filter(line => line !== '').map(line => JSON.parse(line, revive) as {
  testPath: string; testName: string; probe: string; index: number; args: unknown[]; out: unknown;
});

function run(probe: string, args: unknown[]): unknown {
  switch (probe) {
    case 'brief.render': return renderContinuationBriefZh(args[0] as never, args[1] as never);
    case 'brief.approvedMethods': return approvedMethodLinesZh(args[0] as never);
    case 'brief.blockedCommands': return probeBlockedCommandsLinesZh(args[0] as never, args[1] as number, args[2] as boolean);
    case 'unknownCallReview.render': return renderUnknownCallReviewZh(args[0] as never);
    case 'roleProfile': return platformRoleProfile(args[0] as never);
    case 'decisionResponseInput': return formatDecisionResponseInput(args[0] as never);
    case 'architectureReminderRows': return architectureReminderRowEntries(args[0] as never);
    case 'noteHeader': return renderNoteHeader(args[0] as never);
    case 'consultation.guidance': return probeConsultationGuidanceText(args[0] as string, args[1]);
    case 'scribe.reminder': return probeScribeReminderText(args[0] as number, args[1] as number, args[2] as readonly string[]);
    case 'contextExtensions.decisionRow': return probeDecisionRowText(args[0] as never);
    case 'contextExtensions.notAvailableRow': return probeNotAvailableRowText(args[0] as string);
    case 'contextExtensions.anomalyAnchor': return probeAnchorText(args[0] as never);
    default: throw new Error('unknown probe: ' + probe);
  }
}

const lines: string[] = [];
for (const record of records) {
  let out: unknown;
  let error: string | null = null;
  try {
    out = run(record.probe, record.args);
  } catch (caught) {
    error = caught instanceof Error ? caught.message : String(caught);
  }
  lines.push(serializeProbe({
    testPath: record.testPath, testName: record.testName, probe: record.probe, index: record.index, out, error,
  }));
}
writeFileSync(outputPath, lines.join('\\n') + (lines.length === 0 ? '' : '\\n'));

it('replayed every recorded call', () => {
  expect(lines.length).toBe(records.length);
});
`;

writeFileSync(resolve(copyDir, 'tests/probes/replay.generated.test.ts'), generated);

const runResult = spawnSync('npx', ['vitest', 'run', '--maxWorkers=2', 'tests/probes/replay.generated.test.ts'], {
  cwd: copyDir,
  env: { ...process.env, S85_REPLAY_IN: inputLog, S85_REPLAY_OUT: replayOut, S85_PROBE_LOG: '' },
  encoding: 'utf8',
  timeout: 900_000,
});
// The generated test is only for this invocation: remove it so a later full
// suite in the copy never runs a recorder without S85_REPLAY_IN.
const generatedPath = resolve(copyDir, 'tests/probes/replay.generated.test.ts');
try { unlinkSync(generatedPath); } catch { /* already gone */ }
if (runResult.status !== 0) {
  process.stderr.write(runResult.stdout ?? '');
  process.stderr.write(runResult.stderr ?? '');
  console.error(`replay run failed with status ${String(runResult.status)}`);
  process.exit(1);
}

function readJsonl(file, root) {
  const text = readFileSync(file, 'utf8');
  return text.split('\n').filter(line => line !== '').map(line => {
    const record = JSON.parse(line);
    return { ...record, key: [relativeTestPath(root, record.testPath), record.testName, record.probe, record.index].join('\u0000') };
  });
}

const recorded = readJsonl(inputLog, copyDir);
const replayed = new Map(readJsonl(replayOut, copyDir).map(record => [record.key, record]));
const probes = new Map();
let missing = 0;
let differences = 0;

for (const record of recorded) {
  const bucket = probes.get(record.probe) ?? { calls: 0, differences: 0, details: [] };
  bucket.calls += 1;
  probes.set(record.probe, bucket);
  const actual = replayed.get(record.key);
  if (actual === undefined) {
    missing += 1;
    bucket.differences += 1;
    if (bucket.details.length < 20) bucket.details.push({ kind: 'missing-replay', key: record.key });
    continue;
  }
  if (actual.error !== null && actual.error !== undefined) {
    differences += 1;
    bucket.differences += 1;
    if (bucket.details.length < 20) bucket.details.push({ kind: 'replay-error', key: record.key, error: actual.error });
    continue;
  }
  const found = [];
  compareValues(record.out, actual.out, '$', found);
  if (found.length > 0) {
    differences += found.length;
    bucket.differences += found.length;
    if (bucket.details.length < 20) bucket.details.push({ key: record.key, differences: found.slice(0, 5) });
  }
}

const report = {
  copy: copyDir, log: inputLog, replayed: replayOut, label,
  calls: recorded.length, missing, differences,
  probes: Object.fromEntries([...probes.entries()].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([probe, bucket]) => [probe, bucket])),
};
if (reportPath !== '') writeFileSync(resolve(reportPath), JSON.stringify(report, null, 2) + '\n');

console.log(`replayed ${String(recorded.length)} calls on ${label} (${copyDir})`);
for (const [probe, bucket] of Object.entries(report.probes)) {
  console.log(`  ${probe}: calls=${String(bucket.calls)} differences=${String(bucket.differences)}`);
  for (const detail of bucket.details) console.log('    ' + JSON.stringify(detail));
}
if (missing > 0) console.log(`missing replay records: ${String(missing)}`);
if (differences > 0 || missing > 0) process.exit(1);
